"""Deterministically generate the 8 canonical PIP expressions (+2 blink frames).

Outputs:
  artifacts/pip/png/<name>.png        exact 120x120 1-bit PNGs
  artifacts/pip/svg/<name>.svg        pixel-exact SVG (run-length rects)
  artifacts/pip_contact_sheet.png     labelled 4x2 contact sheet
  firmware/assets/pip/pip_sprites.h   packed MSB-first C bitmaps (1 = black ink)
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pip_art as A  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
EXPRESSIONS = ["READY", "LISTENING", "THINKING", "WORKING", "PAUSED", "DONE", "ALARM", "SLEEP"]

GROUND_SHIFT = 5  # art sits 5 px lower so the pads rest near the bottom of the 120 px sprite

# Eyes are drawn procedurally on the device (blink, glance, look-at-text). The sprites in the C header are
# EYELESS; this table tells the firmware how to draw each expression's eyes. Style ids must match mascot.h.
PILL, HAPPY, CLOSED, ANGLED = 0, 1, 2, 3
EYE_SPEC = {  # name: (style, dx, dy, height)
    "READY": (PILL, 0, 0, 14), "LISTENING": (HAPPY, 0, 0, 0), "THINKING": (PILL, 4, -3, 12),
    "WORKING": (ANGLED, 0, 0, 10), "PAUSED": (CLOSED, 0, 0, 0), "DONE": (HAPPY, 0, 0, 0),
    "ALARM": (ANGLED, 0, 0, 12), "SLEEP": (CLOSED, 0, 13, 0),
}


def draw(name: str, eyes: bool = True) -> Image.Image:
    img = _draw(name, eyes)
    out = Image.new("1", img.size, 1)
    out.paste(img.crop((0, 0, A.SIZE, A.SIZE - GROUND_SHIFT)), (0, GROUND_SHIFT))
    return out


def draw_eyes(c: A.Canvas, name: str) -> None:
    style, dx, dy, h = EYE_SPEC[name]
    if style == PILL:
        A.eyes_pill(c, dx=dx, dy=dy, h=h)
    elif style == HAPPY:
        A.eyes_happy(c, dy=dy)
    elif style == CLOSED:
        A.eyes_closed(c, dy=dy)
    else:
        A.eyes_angled(c, dy=dy, intense=h >= 12)


def _draw(name: str, eyes: bool) -> Image.Image:
    c = A.Canvas()
    if name == "SLEEP":
        dy = 8.0
        A.mast(c, dy + 3)
        A.fins(c, dy)
        A.pads(c, 0, tucked=True)
        A.body(c, dy, squash=3)
        A.visor(c, dy + 3)
        A.zzz(c)
    else:
        A.fins(c, raised=name == "DONE")
        A.mast(c)
        A.pads(c, lift_right=(name == "THINKING"))
        A.body(c)
        A.visor(c)
        {"READY": lambda: A.rays(c), "LISTENING": lambda: A.sound_waves(c),
         "THINKING": lambda: (A.raised_pad(c), A.question(c)), "WORKING": lambda: A.laptop(c),
         "PAUSED": lambda: A.mug(c), "DONE": lambda: A.rays(c, cx=102, cy=14, n=3, length=8, spread=(-40, 40)),
         "ALARM": lambda: (A.exclaim(c), A.shake(c))}[name]()
    if eyes:
        draw_eyes(c, name)
    return finish(c)


def finish(c: A.Canvas) -> Image.Image:
    small = c.img.resize((A.SIZE, A.SIZE), Image.BOX)
    return small.point(lambda v: 0 if v < 128 else 255).convert("1")


def pack(img: Image.Image) -> bytes:
    w, h = img.size
    px = img.load()
    out = bytearray()
    for y in range(h):
        for bx in range(0, w, 8):
            b = 0
            for i in range(8):
                if px[bx + i, y] == 0:
                    b |= 0x80 >> i
            out.append(b)
    return bytes(out)


def to_svg(img: Image.Image) -> str:
    w, h = img.size
    px = img.load()
    rects = []
    for y in range(h):
        x = 0
        while x < w:
            if px[x, y] == 0:
                x0 = x
                while x < w and px[x, y] == 0:
                    x += 1
                rects.append(f'<rect x="{x0}" y="{y}" width="{x - x0}" height="1"/>')
            else:
                x += 1
    return (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" '
            f'width="{w * 4}" height="{h * 4}" shape-rendering="crispEdges">'
            f'<rect width="{w}" height="{h}" fill="#fff"/><g fill="#000">{"".join(rects)}</g></svg>')


def contact_sheet(sprites: dict[str, Image.Image]) -> Image.Image:
    cell_w, cell_h, scale = 260, 290, 2
    sheet = Image.new("1", (cell_w * 4, cell_h * 2), 1)
    d = ImageDraw.Draw(sheet)
    font = ImageFont.load_default(size=20)
    for i, name in enumerate(EXPRESSIONS):
        cx, cy = (i % 4) * cell_w, (i // 4) * cell_h
        big = sprites[name].resize((A.SIZE * scale, A.SIZE * scale), Image.NEAREST)
        sheet.paste(big, (cx + (cell_w - A.SIZE * scale) // 2, cy + 10))
        tw = d.textlength(name, font=font)
        d.text((cx + (cell_w - tw) / 2, cy + 258), name, fill=0, font=font)
    return sheet


def header(eyeless: dict[str, Image.Image]) -> str:
    names = EXPRESSIONS
    lx, ly = A.EYE_L
    rx, ry = A.EYE_R
    lines = [
        "/* GENERATED by tools/generate_pip_assets.py - do not edit. */",
        "#ifndef PIP_SPRITES_H", "#define PIP_SPRITES_H", "#include <stdint.h>",
        "#define PIP_SPRITE_W 120", "#define PIP_SPRITE_H 120",
        "#define PIP_SPRITE_STRIDE 15", "#define PIP_SPRITE_BYTES 1800",
        f"#define PIP_SPRITE_COUNT {len(names)}",
        "/* Sprites are EYELESS: eyes are drawn live (blink / glance / look-at-text). */",
        f"#define PIP_EYE_L_X {lx}", f"#define PIP_EYE_L_Y {ly + GROUND_SHIFT}",
        f"#define PIP_EYE_R_X {rx}", f"#define PIP_EYE_R_Y {ry + GROUND_SHIFT}",
        "/* per expression: style (0 pill, 1 happy, 2 closed, 3 angled), dx, dy, height */",
        "static const int8_t pip_eye_spec[PIP_SPRITE_COUNT][4] = {",
        *[f"  {{{EYE_SPEC[n][0]}, {EYE_SPEC[n][1]}, {EYE_SPEC[n][2]}, {EYE_SPEC[n][3]}}}, /* {n} */" for n in names],
        "};",
    ]
    lines.append("static const uint8_t pip_sprites[PIP_SPRITE_COUNT][PIP_SPRITE_BYTES] = {")
    for n in names:
        data = pack(eyeless[n])
        lines.append(f"  /* {n} */ {{")
        for off in range(0, len(data), 15):
            lines.append("    " + ",".join(f"0x{b:02X}" for b in data[off:off + 15]) + ",")
        lines.append("  },")
    lines += ["};", "#endif", ""]
    return "\n".join(lines)


def main() -> int:
    out_png = ROOT / "artifacts/pip/png"
    out_svg = ROOT / "artifacts/pip/svg"
    out_png.mkdir(parents=True, exist_ok=True)
    out_svg.mkdir(parents=True, exist_ok=True)
    sprites = {n: draw(n) for n in EXPRESSIONS}  # with eyes: review PNGs, SVGs and contact sheet
    for n, img in sprites.items():
        assert img.size == (120, 120) and img.mode == "1"
        img.save(out_png / f"{n.lower()}.png")
        (out_svg / f"{n.lower()}.svg").write_text(to_svg(img), encoding="utf-8")
    for stale in ("ready_blink", "working_blink"):  # replaced by live procedural blinking
        for p in (out_png / f"{stale}.png", out_svg / f"{stale}.svg"):
            p.unlink(missing_ok=True)
    contact_sheet(sprites).save(ROOT / "artifacts/pip_contact_sheet.png")
    hdr = ROOT / "firmware/assets/pip/pip_sprites.h"
    hdr.parent.mkdir(parents=True, exist_ok=True)
    hdr.write_text(header({n: draw(n, eyes=False) for n in EXPRESSIONS}), encoding="utf-8", newline="\n")
    print(f"generated {len(sprites)} sprites -> {hdr.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
